//ENCAPSULAMIENTO:
//Esta característica permite ver un objeto como una caja negra en la que se ha introducido de alguna manera
//toda la información relacionada con dicho objeto.
//Esto nos permitirá manipular los objetos como unidades básicas, permaneciendo oculta su estructura interna.
//La abstracción y la encapsulación están representadas por la clase. La clase es una abstracción,
//porque en ella se definen las propiedades o atributos de un determinado conjunto de objetos
//con características comunes, y es una encapsulación porque constituye una caja negra que encierra tanto los
//datos que almacena cada objeto como los métodos que permiten manipularlos.


//HERENCIA:
//La herencia permite el acceso automático a la información contenida en otras clases. De esta forma, la
//reutilización del código está garantizada. Con la herencia
//todas las clases están clasificadas en una jerarquía estricta. Cada clase tiene su superclase
//(la clase superior en la jerarquía), y cada clase puede tener una o más
//subclases (las clases inferiores en la jerarquía).
//
//                                    %CLASE CO ORDENADOR%
//  %CLASE CO ORDENADOR SOBRE MESA%                         %CLASE CO ORDENADOR PORTATIL%
//
//Las clases que están en la parte inferior en la jerarquía se dice que heredan de las clases que están
// en la parte superior en la jerarquía.
//El término heredar significa que las subclases disponen de todos los métodos y propiedades de su superclase.
// Este mecanismo proporciona una forma rápida y cómoda de extender la funcionalidad de una clase.


//POLIFORMISMO:
//Esta característica permite implementar múltiples formas de un mismo método,
//dependiendo cada una de ellas de la clase sobre la que se realice la implementación.
// Esto hace que se pueda acceder a una variedad de métodos distintos (todos
//con el mismo nombre) utilizando exactamente el mismo medio de acceso. Más
//adelante, cuando estudie en profundidad las clases y subclases, estará en condiciones de entender
// con claridad la utilidad de esta característica.

